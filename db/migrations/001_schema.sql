REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC;
GRANT USAGE ON SCHEMA private TO authenticated;

CREATE FUNCTION private.claims() RETURNS jsonb
LANGUAGE sql STABLE SET search_path = pg_catalog AS $$
  SELECT coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb)
$$;
CREATE FUNCTION private.user_id() RETURNS uuid
LANGUAGE sql STABLE SET search_path = pg_catalog AS $$
  SELECT nullif(private.claims()->>'sub', '')::uuid
$$;
CREATE FUNCTION private.has_role(role_name text) RETURNS boolean
LANGUAGE sql STABLE SET search_path = pg_catalog AS $$
  SELECT coalesce(private.claims()->'realm_access'->'roles' ? role_name, false)
$$;
CREATE FUNCTION private.is_staff() RETURNS boolean
LANGUAGE sql STABLE SET search_path = pg_catalog AS $$
  SELECT private.has_role('Agent') OR private.has_role('Manager')
$$;

CREATE TABLE public.categories (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_-]{1,39}$'),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
  description text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.sla_policies (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  priority text NOT NULL UNIQUE CHECK (priority IN ('low', 'normal', 'high', 'critical')),
  response_minutes integer NOT NULL CHECK (response_minutes > 0),
  resolution_minutes integer NOT NULL CHECK (resolution_minutes >= response_minutes)
);
CREATE TABLE public.routing_rules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category_id uuid NOT NULL UNIQUE REFERENCES public.categories(id),
  team text NOT NULL CHECK (length(btrim(team)) BETWEEN 1 AND 100),
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.tickets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  requester_id uuid NOT NULL DEFAULT private.user_id(),
  category_id uuid NOT NULL REFERENCES public.categories(id),
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 5 AND 200),
  description text NOT NULL CHECK (length(btrim(description)) BETWEEN 10 AND 5000),
  priority text NOT NULL DEFAULT 'normal' REFERENCES public.sla_policies(priority),
  status text NOT NULL DEFAULT 'new' CHECK (
    status IN ('new', 'triaged', 'assigned', 'in_progress', 'resolved', 'closed', 'cancelled')
  ),
  assigned_to uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX tickets_requester_created_idx ON public.tickets(requester_id, created_at DESC);
CREATE INDEX tickets_assignee_idx ON public.tickets(assigned_to) WHERE assigned_to IS NOT NULL;
CREATE INDEX tickets_status_created_idx ON public.tickets(status, created_at DESC);
CREATE TABLE public.ticket_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id uuid NOT NULL REFERENCES public.tickets(id) ON DELETE RESTRICT,
  actor_id uuid NOT NULL,
  event_type text NOT NULL CHECK (event_type IN ('created', 'status_changed')),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ticket_events_ticket_created_idx ON public.ticket_events(ticket_id, created_at);
CREATE TABLE public.attachments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id uuid NOT NULL REFERENCES public.tickets(id) ON DELETE RESTRICT,
  uploaded_by uuid NOT NULL DEFAULT private.user_id(),
  file_name text NOT NULL CHECK (length(file_name) BETWEEN 1 AND 255),
  object_key text NOT NULL UNIQUE,
  content_type text NOT NULL,
  size_bytes bigint NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 10485760),
  scan_status text NOT NULL DEFAULT 'pending' CHECK (scan_status IN ('pending', 'clean', 'infected', 'failed')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attachments_ticket_idx ON public.attachments(ticket_id);
CREATE TABLE public.device_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  requester_id uuid NOT NULL DEFAULT private.user_id(),
  device_type text NOT NULL CHECK (device_type IN ('laptop', 'monitor', 'keyboard', 'mouse', 'other')),
  reason text NOT NULL CHECK (length(btrim(reason)) BETWEEN 10 AND 2000),
  quantity integer NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'fulfilled')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX device_requests_requester_idx ON public.device_requests(requester_id, created_at DESC);

-- Audit is generated by PostgreSQL, not accepted from a browser or API body.
CREATE FUNCTION private.audit_ticket_created() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
BEGIN
  INSERT INTO public.ticket_events(ticket_id, actor_id, event_type, payload)
  VALUES (NEW.id, NEW.requester_id, 'created', jsonb_build_object('status', NEW.status));
  RETURN NEW;
END
$$;
CREATE TRIGGER ticket_created AFTER INSERT ON public.tickets
FOR EACH ROW EXECUTE FUNCTION private.audit_ticket_created();

REVOKE ALL ON ALL FUNCTIONS IN SCHEMA private FROM PUBLIC;
GRANT EXECUTE ON FUNCTION private.claims(), private.user_id(), private.has_role(text), private.is_staff()
TO authenticated;
